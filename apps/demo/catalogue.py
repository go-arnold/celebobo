from dataclasses import dataclass, field
from decimal import Decimal

from apps.catalog.domain.enums import Badge, CategoryIcon


@dataclass(frozen=True, slots=True)
class DemoCategory:
    key: str
    name: str
    icon: CategoryIcon
    description: str
    color: tuple[str, str]


@dataclass(frozen=True, slots=True)
class DemoProduct:
    category: str
    name: str
    brand: str
    shape: str
    price: str
    cost: str
    stock: int
    description: str
    features: tuple[str, ...]
    sale_price: str | None = None
    badge: Badge | None = None
    free_shipping: bool = False
    options: dict[str, tuple[str, ...]] = field(default_factory=dict)
    variants: tuple[tuple[dict[str, str], str | None, int], ...] = ()
    # verified Pexels photo ids: the first is the main image, the others fill the gallery
    photos: tuple[int, ...] = ()

    @property
    def money(self) -> tuple[Decimal, Decimal | None, Decimal]:
        sale = Decimal(self.sale_price) if self.sale_price else None
        return Decimal(self.price), sale, Decimal(self.cost)


